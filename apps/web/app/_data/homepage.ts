import registry from "../../../../data/territories/departments-v1.1.json" with { type: "json" };

export type HomeLocale = "ht" | "fr";

export const departments = registry.records.map((record) => ({
  id: record.departmentId,
  name: record.name,
  capital: record.capital,
  communes: record.communeCount,
  arrondissements: record.arrondissementCount,
  sections: record.communalSectionCount,
}));

export const territoryTotals = {
  departments: departments.length,
  communes: departments.reduce((total, department) => total + department.communes, 0),
  arrondissements: departments.reduce((total, department) => total + department.arrondissements, 0),
  sections: departments.reduce((total, department) => total + department.sections, 0),
};

export const territorySource = {
  url: registry.records[0]?.sourceUrl,
  verifiedAt: registry.sourceVerifiedAt.slice(0, 10),
};

